/**
 * Detect if the currently connected wallet is on Solana
 */
function isSolanaConnected() {
  const address = modal.getAddress()
  // EVM addresses start with 0x, Solana addresses are base58 (no 0x prefix)
  return address && !address.startsWith('0x')
}

/**
 * Get the current connected wallet address
 * @returns {string|null} The connected address or null
 */
export function getAddress() {
  if (TEST_MODE && testAccount) {
    return testAccount.address
  }
  return modal.getAddress()
}

/**
 * Check if wallet is connected
 * @returns {boolean}
 */
export function isConnected() {
  if (TEST_MODE && testAccount) {
    return true  // Always connected in test mode
  }
  return modal.getIsConnectedState()
}

/**
 * Open the wallet connection modal
 */
export async function openModal() {
  if (TEST_MODE) {
    console.log('TEST MODE: Skipping wallet modal, using test account:', testAccount?.address)
    return
  }
  await modal.open()
}

/**
 * Get the wallet provider for signing
 * @returns {Promise<any>} The wallet provider
 */
export async function getProvider() {
  const provider = modal.getWalletProvider()
  if (!provider) {
    throw new Error('No wallet provider available')
  }
  return provider
}

/**
 * Create a ClientEvmSigner that wraps the browser wallet provider
 * This adapter converts the wallet provider's eth_signTypedData_v4 method
 * to the interface expected by @x402/evm
 */
async function createWalletSigner() {
  const address = getAddress()
  if (!address) {
    throw new Error('No wallet connected')
  }

  const provider = await getProvider()

  return {
    address: checksumAddress(address),
    async signTypedData({ domain, types, primaryType, message }) {
      console.log('[x402] Signing typed data with wallet provider')
      console.log('[x402] Domain:', domain)
      console.log('[x402] Message:', message)

      // Prepare typed data for eth_signTypedData_v4
      // Convert BigInts to strings for JSON serialization
      const serializableMessage = {}
      for (const [key, value] of Object.entries(message)) {
        if (typeof value === 'bigint') {
          // Use decimal strings for uint256 values
          serializableMessage[key] = value.toString()
        } else {
          serializableMessage[key] = value
        }
      }

      const typedData = {
        domain,
        types: {
          // EIP712Domain is typically auto-generated by wallets, but include it for safety
          EIP712Domain: [
            { name: 'name', type: 'string' },
            { name: 'version', type: 'string' },
            { name: 'chainId', type: 'uint256' },
            { name: 'verifyingContract', type: 'address' }
          ],
          ...types
        },
        primaryType,
        message: serializableMessage
      }

      console.log('[x402] Serialized typed data:', JSON.stringify(typedData, null, 2))

      const signature = await provider.request({
        method: 'eth_signTypedData_v4',
        params: [address, JSON.stringify(typedData)]
      })

      console.log('[x402] Signature obtained:', signature.slice(0, 20) + '...')
      return signature
    }
  }
}

// Well-known Solana program addresses
const TOKEN_PROGRAM_ID = new PublicKey('TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA')
const TOKEN_2022_PROGRAM_ID = new PublicKey('TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb')
const ASSOCIATED_TOKEN_PROGRAM_ID = new PublicKey('ATokenGPvbdGVxr1b2hvZbsiqW5xWH25efTNsLJA8knL')

/**
 * Compute the Associated Token Account address for an owner + mint
 */
function findAssociatedTokenAddress(owner, mint, tokenProgramId) {
  const [address] = PublicKey.findProgramAddressSync(
    [owner.toBuffer(), tokenProgramId.toBuffer(), mint.toBuffer()],
    ASSOCIATED_TOKEN_PROGRAM_ID
  )
  return address
}

/**
 * Build an SPL Token TransferChecked instruction manually
 * (avoids needing @solana/spl-token as a dependency)
 */
function buildTransferCheckedInstruction(source, mint, destination, authority, amount, decimals, tokenProgramId) {
  // TransferChecked instruction: discriminator 12, then u64 amount (LE), then u8 decimals
  const data = new Uint8Array(10)
  data[0] = 12
  const view = new DataView(data.buffer)
  view.setBigUint64(1, BigInt(amount), true)
  data[9] = decimals

  return new TransactionInstruction({
    programId: tokenProgramId,
    keys: [
      { pubkey: source, isSigner: false, isWritable: true },
      { pubkey: mint, isSigner: false, isWritable: false },
      { pubkey: destination, isSigner: false, isWritable: true },
      { pubkey: authority, isSigner: true, isWritable: false },
    ],
    data
  })
}

/**
 * Custom SVM payment scheme built entirely with @solana/web3.js v1.
 * Bypasses @solana/kit v2 (which produces malformed transactions when imported
 * alongside @x402/svm due to Vite bundling issues) and omits the Memo instruction
 * that the CDP facilitator rejects.
 *
 * Builds 3-instruction transactions: ComputeUnitLimit, ComputeUnitPrice, TransferChecked.
 */
class SolanaPaymentScheme {
  constructor(walletProvider, walletAddress, config) {
    this.walletProvider = walletProvider
    this.walletAddress = walletAddress
    this.rpcUrl = config?.rpcUrl
    this.scheme = 'exact'
  }

  async createPaymentPayload(x402Version, paymentRequirements) {
    const connection = new Connection(this.rpcUrl)

    const mint = new PublicKey(paymentRequirements.asset)
    const payTo = new PublicKey(paymentRequirements.payTo)
    const authority = new PublicKey(this.walletAddress)
    const feePayer = paymentRequirements.extra?.feePayer
    if (!feePayer) {
      throw new Error('feePayer is required in paymentRequirements.extra for SVM transactions')
    }
    const feePayerKey = new PublicKey(feePayer)

    // Get mint info to determine token program and decimals
    const mintInfo = await connection.getAccountInfo(mint)
    if (!mintInfo) throw new Error('Mint account not found')

    const tokenProgramId = mintInfo.owner.equals(TOKEN_2022_PROGRAM_ID)
      ? TOKEN_2022_PROGRAM_ID
      : TOKEN_PROGRAM_ID

    // Parse decimals from mint data layout (offset 44)
    const decimals = mintInfo.data[44]

    // Compute Associated Token Accounts
    const sourceATA = findAssociatedTokenAddress(authority, mint, tokenProgramId)
    const destATA = findAssociatedTokenAddress(payTo, mint, tokenProgramId)

    // Get latest blockhash
    const { blockhash } = await connection.getLatestBlockhash()

    // Build 3-instruction transaction (no Memo)
    const instructions = [
      ComputeBudgetProgram.setComputeUnitLimit({ units: 20000 }),
      ComputeBudgetProgram.setComputeUnitPrice({ microLamports: 1 }),
      buildTransferCheckedInstruction(
        sourceATA, mint, destATA, authority,
        paymentRequirements.amount, decimals, tokenProgramId
      )
    ]

    const messageV0 = new TransactionMessage({
      payerKey: feePayerKey,
      recentBlockhash: blockhash,
      instructions
    }).compileToV0Message()

    const vt = new VersionedTransaction(messageV0)

    // Have the wallet sign the transaction
    console.log('[x402] Signing Solana transaction with wallet provider')
    const signedVt = await this.walletProvider.signTransaction(vt)
    console.log('[x402] Solana signature obtained')

    // Serialize to base64
    const serialized = signedVt.serialize()
    const base64 = btoa(serialized.reduce((s, b) => s + String.fromCharCode(b), ''))

    return {
      x402Version,
      payload: { transaction: base64 }
    }
  }
}

/**
 * Create an x402 fetch client with the appropriate signer for the connected wallet
 */
async function createX402Fetch() {
  const client = new x402Client()

  if (TEST_MODE && testAccount) {
    console.log('[x402] Using test account as signer (EVM)')
    registerExactEvmScheme(client, { signer: testAccount })
  } else if (isSolanaConnected()) {
    console.log('[x402] Creating Solana payment scheme')
    const address = getAddress()
    const provider = solanaProvider || await getProvider()
    // Use @solana/web3.js v1 scheme with server-side RPC proxy
    // (bypasses @solana/kit v2 bundling issues and omits Memo instruction)
    const solanaRpcUrl = `${window.location.origin}/api/solana-rpc`
    client.register('solana:*', new SolanaPaymentScheme(provider, address, { rpcUrl: solanaRpcUrl }))
  } else {
    console.log('[x402] Creating EVM wallet signer')
    const signer = await createWalletSigner()
    registerExactEvmScheme(client, { signer })
  }

  return wrapFetchWithPayment(fetch, client)
}

/**
 * Get the appropriate block explorer URL for a transaction
 */
function getExplorerUrl(transaction) {
  if (isSolanaConnected()) {
    return `https://solscan.io/tx/${transaction}`
  }
  return `https://basescan.org/tx/${transaction}`
}

/**
 * Fetch wrapper that handles x402 payments automatically using the official @x402/fetch library
 * @param {string} url - The URL to fetch
 * @param {object} options - Fetch options
 * @returns {Promise<Response>}
 */
export async function fetchWithPayment(url, options = {}) {
  console.log('%c[x402] fetchWithPayment', 'color: #6366f1; font-weight: bold')
  console.log('[x402] URL:', url)
  console.log('[x402] Method:', options.method || 'GET')

  if (options.body) {
    try {
      console.log('[x402] Body:', JSON.parse(options.body))
    } catch {
      console.log('[x402] Body:', options.body)
    }
  }

  // Check if wallet is connected (for non-test mode)
  if (!TEST_MODE && !isConnected()) {
    console.log('[x402] Wallet not connected, opening modal...')
    await openModal()
    // Wait for connection
    await new Promise((resolve, reject) => {
      const checkConnection = setInterval(() => {
        if (isConnected()) {
          clearInterval(checkConnection)
          resolve()
        }
      }, 500)
      // Timeout after 60 seconds
      setTimeout(() => {
        clearInterval(checkConnection)
        reject(new Error('Wallet connection timeout'))
      }, 60000)
    })
  }

  try {
    // Create x402-wrapped fetch
    const x402Fetch = await createX402Fetch()

    // Make the request - x402 library handles 402 responses automatically
    const response = await x402Fetch(url, options)

    console.log('[x402] Response status:', response.status, response.statusText)

    if (response.ok) {
      console.log('%c[x402] Request successful', 'color: #10b981; font-weight: bold')

      // Check for payment response header
      const paymentResponseHeader = response.headers.get('PAYMENT-RESPONSE')
      if (paymentResponseHeader) {
        try {
          const settlementResult = JSON.parse(atob(paymentResponseHeader))
          if (settlementResult?.success && settlementResult?.transaction) {
            console.log('%c[x402] Payment settled on-chain!', 'color: #10b981; font-weight: bold; font-size: 14px')
            const explorerUrl = getExplorerUrl(settlementResult.transaction)
            console.log('[x402] View transaction:', explorerUrl)
          }
        } catch (e) {
          // Ignore parse errors
        }
      }
    } else {
      console.error('%c[x402] Request failed', 'color: #ef4444; font-weight: bold')
      console.error('[x402] Status:', response.status)

      // Log error details
      const errorHeader = response.headers.get('PAYMENT-REQUIRED')
      if (errorHeader) {
        try {
          const errorData = JSON.parse(atob(errorHeader))
          console.error('[x402] Error:', errorData.error || errorData)
        } catch (e) {
          // Ignore parse errors
        }
      }
    }

    return response
  } catch (error) {
    console.error('%c[x402] Fetch error', 'color: #ef4444; font-weight: bold')
    console.error('[x402] Error:', error)
    throw error
  }
}

